import { defineSchema, defineTable } from "convex/server";
import { v } from "convex/values";

export default defineSchema({
  hotels: defineTable({
    customId: v.optional(v.string()),
    displayOrder: v.optional(v.number()),
    name: v.string(),
    location: v.string(),
    region: v.string(),
    category: v.string(),
    price: v.number(),
    originalPrice: v.number(),
    discount: v.number(),
    images: v.array(v.string()),
    tag: v.optional(v.string()),
    isMain: v.optional(v.boolean()),
    desc: v.optional(v.string()),
    benefit: v.optional(v.string()),
    source: v.optional(v.string()),
    rating: v.optional(v.number()),
  }).index("by_category", ["category"]).index("by_region", ["region"]).index("by_customId", ["customId"]),

  coupons: defineTable({
    code: v.string(),
    num: v.optional(v.number()),
    couponNumber: v.optional(v.number()),
    status: v.string(), // "NOT_ISSUED", "ISSUED", "REGISTERED", "USED"
    branch: v.optional(v.string()),
    assignedUser: v.optional(v.string()),
    assignedTo: v.optional(v.string()),
    userPhone: v.optional(v.string()),
    assignedPhone: v.optional(v.string()),
    registeredAt: v.optional(v.string()),
    assignedDate: v.optional(v.string()),
    usedAt: v.optional(v.string()),
    usedDate: v.optional(v.string()),
    usedFor: v.optional(v.string()),
    reservationId: v.optional(v.string()),
    memo: v.optional(v.string()),
  }).index("by_code", ["code"]).index("by_status", ["status"]).index("by_num", ["num"]),

  allocations: defineTable({
    id: v.string(),
    startNum: v.number(),
    endNum: v.number(),
    branch: v.string(),
    memo: v.optional(v.string()),
    count: v.number(),
    createdAt: v.string(),
  }).index("by_branch", ["branch"]),

  reservations: defineTable({
    customId: v.optional(v.string()),
    hotelId: v.optional(v.string()),
    hotelName: v.string(),
    hotelLocation: v.optional(v.string()),
    userName: v.string(),
    phone: v.optional(v.string()),
    userPhone: v.optional(v.string()),
    couponCode: v.optional(v.string()),
    checkIn: v.string(),
    checkOut: v.string(),
    nights: v.optional(v.number()),
    guests: v.optional(v.number()),
    adults: v.optional(v.number()),
    children: v.optional(v.number()),
    address: v.optional(v.string()),
    addressDetail: v.optional(v.string()),
    postcode: v.optional(v.string()),
    totalPrice: v.optional(v.number()),
    finalPayment: v.optional(v.number()),
    status: v.string(), // "접수대기", "확정완료", "취소"
    requests: v.optional(v.string()),
    requestMemo: v.optional(v.string()),
    createdAt: v.union(v.number(), v.string()),
  }).index("by_status", ["status"]),

  inquiries: defineTable({
    customId: v.optional(v.string()),
    name: v.string(),
    phone: v.string(),
    title: v.optional(v.string()),
    category: v.optional(v.string()),
    preferredTime: v.optional(v.string()),
    content: v.string(),
    status: v.string(), // "상담대기", "상담완료"
    memo: v.optional(v.string()),
    reply: v.optional(v.string()),
    createdAt: v.union(v.number(), v.string()),
  }).index("by_phone", ["phone"]).index("by_status", ["status"]),

  otherProducts: defineTable({
    customId: v.string(),
    category: v.string(),
    name: v.string(),
    location: v.string(),
    region: v.string(),
    price: v.number(),
    originalPrice: v.number(),
    discount: v.number(),
    images: v.array(v.string()),
    tag: v.optional(v.string()),
    desc: v.optional(v.string()),
    benefit: v.optional(v.string()),
    isMain: v.optional(v.boolean()),
    rating: v.optional(v.number()),
  }).index("by_category", ["category"]).index("by_customId", ["customId"]),

  admins: defineTable({
    id: v.string(),
    username: v.string(),
    password: v.string(),
    name: v.string(),
    role: v.string(),
    roleName: v.string(),
    department: v.string(),
    phone: v.string(),
    email: v.string(),
    status: v.string(),
    createdAt: v.string(),
    lastLogin: v.optional(v.string()),
    memo: v.optional(v.string()),
  }).index("by_username", ["username"]),

  adminLogs: defineTable({
    id: v.string(),
    adminId: v.string(),
    adminName: v.string(),
    action: v.string(),
    actionName: v.string(),
    details: v.string(),
    createdAt: v.string(),
  }).index("by_createdAt", ["createdAt"]),
});
